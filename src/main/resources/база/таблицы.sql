CREATE TABLE IF NOT EXISTS спектакли (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    название VARCHAR(200) NOT NULL CHECK (LENGTH(TRIM(название)) > 0),
    длительность_минут INTEGER NOT NULL CHECK (длительность_минут > 0),
    возрастное_ограничение INTEGER NOT NULL CHECK (возрастное_ограничение >= 0)
);

CREATE TABLE IF NOT EXISTS залы (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    название VARCHAR(200) NOT NULL CHECK (LENGTH(TRIM(название)) > 0),
    число_мест INTEGER NOT NULL CHECK (число_мест > 0)
);

CREATE TABLE IF NOT EXISTS пользователи (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    имя VARCHAR(200) NOT NULL CHECK (LENGTH(TRIM(имя)) > 0)
);

CREATE TABLE IF NOT EXISTS показы (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    спектакль_id BIGINT NOT NULL REFERENCES спектакли(id) ON DELETE RESTRICT,
    зал_id BIGINT NOT NULL REFERENCES залы(id) ON DELETE RESTRICT,
    начало TIMESTAMP NOT NULL,
    базовая_цена DECIMAL(12, 2) NOT NULL CHECK (базовая_цена >= 0),
    статус VARCHAR(30) NOT NULL CHECK (статус IN ('ЗАПЛАНИРОВАН', 'ОТМЕНЁН', 'ЗАВЕРШЁН'))
);

CREATE TABLE IF NOT EXISTS билеты (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    показ_id BIGINT NOT NULL REFERENCES показы(id) ON DELETE RESTRICT,
    номер_места INTEGER NOT NULL CHECK (номер_места > 0),
    пользователь_id BIGINT NOT NULL REFERENCES пользователи(id) ON DELETE RESTRICT,
    статус VARCHAR(30) NOT NULL CHECK (статус IN ('БРОНЬ', 'КУПЛЕН', 'ВОЗВРАЩЁН', 'ОТМЕНЁН', 'ИСПОЛЬЗОВАН')),
    цена DECIMAL(12, 2) NOT NULL CHECK (цена >= 0),
    сумма_возврата DECIMAL(12, 2) NOT NULL DEFAULT 0 CHECK (сумма_возврата >= 0 AND сумма_возврата <= цена),
    активное_место INTEGER GENERATED ALWAYS AS (
        CASE WHEN статус IN ('БРОНЬ', 'КУПЛЕН', 'ИСПОЛЬЗОВАН') THEN номер_места ELSE NULL END
    ),
    CHECK (статус <> 'БРОНЬ' OR (цена = 0 AND сумма_возврата = 0)),
    CHECK (статус NOT IN ('КУПЛЕН', 'ИСПОЛЬЗОВАН') OR сумма_возврата = 0),
    CHECK (статус NOT IN ('ВОЗВРАЩЁН', 'ОТМЕНЁН') OR сумма_возврата = цена),
    UNIQUE (показ_id, активное_место)
);

-- Одна строка позволяет последовательно выполнять связанные изменения в транзакциях.
CREATE TABLE IF NOT EXISTS блокировка (
    id INTEGER PRIMARY KEY CHECK (id = 1)
);
INSERT INTO блокировка (id) SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM блокировка);

-- Отметка не позволяет возвращать удалённые примеры при повторном запуске.
CREATE TABLE IF NOT EXISTS подготовка (
    id INTEGER PRIMARY KEY CHECK (id = 1)
);
